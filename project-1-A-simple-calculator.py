# SIMPLE CALCULATOR IN PYTHON
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

print("The sum of ", a, "+" , b, "is:", a+b)
print("The difference of ", a, "-" , b, "is:", a-b)
print("The quotient of ", a, "/" , b, "is:", a/b)
print("The product of ", a, "*" , b, "is:", a*b)
print("The power of ", a, "**" , b, "is:", a**b)
print("The remainder of ", a, "%" , b, "is:", a%b)
print("The floor division of ", a, "//" , b, "is:", a//b) #floor divison means ki agar answer decimal me aata hai to usko round off karke nearest integer me convert kar deta hai.



